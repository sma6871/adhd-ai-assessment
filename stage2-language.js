function t2() { return window.STAGE2_LANG[window.STAGE2_STATE.lang] || window.STAGE2_LANG.en; }
function esc(s) { return String(s || '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])); }
function byId(id) { return document.getElementById(id); }

function faDigits(s) {
  return String(s).replace(/\d/g, function (d) {
    const farsi = '۰۱۲۳۴۵۶۷۸۹';
    return farsi[d];
  });
}
function num(n) {
  return window.STAGE2_STATE.lang === 'fa' ? faDigits(n) : String(n);
}
